-- H.M PST promo codes: independent migration; does not alter products or existing discounts.
create table if not exists public.promo_codes (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9]{5}$'),
  discount_price numeric(10,2) not null default 200 check (discount_price = 200),
  assigned_visitor uuid unique,
  is_used boolean not null default false,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.promo_codes enable row level security;

drop policy if exists "promo admins read" on public.promo_codes;
create policy "promo admins read" on public.promo_codes
for select to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = auth.uid()));

drop policy if exists "promo admins manage" on public.promo_codes;
create policy "promo admins manage" on public.promo_codes
for all to authenticated
using (exists (select 1 from public.store_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.store_admins a where a.user_id = auth.uid()));

create or replace function public.issue_hm_promo_code(p_visitor uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_count integer;
  v_try integer;
begin
  if p_visitor is null then raise exception 'visitor id required'; end if;
  select code into v_code from public.promo_codes
   where assigned_visitor = p_visitor and not is_used limit 1;
  if v_code is not null then return v_code; end if;

  select count(*) into v_count from public.promo_codes;
  if v_count >= 100 then raise exception 'promo campaign is full'; end if;

  for v_try in 1..30 loop
    v_code := upper(substr(encode(gen_random_bytes(4),'hex'),1,5));
    begin
      insert into public.promo_codes(code, assigned_visitor)
      values (v_code, p_visitor);
      return v_code;
    exception when unique_violation then
      null;
    end;
  end loop;
  raise exception 'could not allocate promo code';
end;
$$;

create or replace function public.check_hm_promo_code(p_code text)
returns table(valid boolean, discount_price numeric, message text)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  select (not p.is_used), p.discount_price,
         case when p.is_used then 'الكود مستخدم بالفعل' else 'تم التحقق من الكود' end
  from public.promo_codes p
  where p.code = upper(trim(p_code))
  limit 1;
  if not found then
    return query select false, null::numeric, 'الكود غير صحيح';
  end if;
end;
$$;

-- Only the store owner/admin can mark a code used after confirming an order.
create or replace function public.consume_hm_promo_code(p_code text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.store_admins a where a.user_id = auth.uid()) then
    raise exception 'admin only';
  end if;
  update public.promo_codes
     set is_used = true, used_at = now()
   where code = upper(trim(p_code)) and not is_used;
  return found;
end;
$$;

revoke all on function public.issue_hm_promo_code(uuid) from public;
grant execute on function public.issue_hm_promo_code(uuid) to anon, authenticated;
revoke all on function public.check_hm_promo_code(text) from public;
grant execute on function public.check_hm_promo_code(text) to anon, authenticated;
revoke all on function public.consume_hm_promo_code(text) from public;
grant execute on function public.consume_hm_promo_code(text) to authenticated;

-- Admin bulk generation and visitor assignment from the pre-generated pool.
create or replace function public.generate_hm_promo_codes()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v_added integer := 0; v_code text; v_try integer;
begin
  if not exists (select 1 from public.store_admins a where a.user_id = auth.uid()) then
    raise exception 'admin only';
  end if;
  if (select count(*) from public.promo_codes) >= 100 then
    raise exception 'campaign already has 100 codes';
  end if;
  while (select count(*) from public.promo_codes) < 100 loop
    v_code := upper(substr(encode(gen_random_bytes(4),'hex'),1,5));
    begin
      insert into public.promo_codes(code) values(v_code);
      v_added := v_added + 1;
    exception when unique_violation then null;
    end;
  end loop;
  return v_added;
end;
$$;

create or replace function public.issue_hm_promo_code(p_visitor uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare v_code text;
begin
  if p_visitor is null then raise exception 'visitor id required'; end if;
  select code into v_code from public.promo_codes
   where assigned_visitor = p_visitor and not is_used limit 1;
  if v_code is not null then return v_code; end if;
  update public.promo_codes
     set assigned_visitor = p_visitor
   where id = (select id from public.promo_codes
               where assigned_visitor is null and not is_used
               order by id limit 1 for update skip locked)
   returning code into v_code;
  if v_code is null then raise exception 'no promo codes available'; end if;
  return v_code;
end;
$$;

revoke all on function public.generate_hm_promo_codes() from public;
grant execute on function public.generate_hm_promo_codes() to authenticated;

